#!/usr/bin/env python3
"""Turn the raw `oc get -o json` exports in ngc-809/_live-export/ into clean, re-applyable YAML manifests.

Strips server-side/runtime fields (uid, resourceVersion, generation, creationTimestamp, managedFields,
ownerReferences, status, last-applied/webhook annotations). Pods are taken from their
kubectl.kubernetes.io/last-applied-configuration (the exact spec that was applied), so fields injected
at admission (kube-api-access / podnetinfo volumes, default tolerations, env) are not duplicated.
Writes the numbered manifests into ngc-809/ in apply order.
Usage: python3 ngc-809/tools/clean_export.py   (run from the repo root)
"""
import json
import os
import yaml

BASE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
RAW = os.path.join(BASE, "_live-export")
DROP_META = {"uid", "resourceVersion", "generation", "creationTimestamp", "managedFields",
             "ownerReferences", "selfLink", "finalizers"}
DROP_ANN_PREFIX = ("kubectl.kubernetes.io/last-applied-configuration", "nmstate.io/webhook-mutating-timestamp",
                   "openshift.io/sa.scc.", "security.openshift.io/", "k8s.ovn.org/", "k8s.v1.cni.cncf.io/network-status",
                   "openshift.io/scc", "sriovnetwork.openshift.io/owner-ref", "nmstate.io/force-reconcile")
DROP_LABELS = {"kubernetes.io/metadata.name"}


def load(name):
    d = json.load(open(os.path.join(RAW, name)))
    return d["items"] if "items" in d else [d]


def clean(o):
    if o["kind"] == "Pod":
        o = json.loads(o["metadata"]["annotations"]["kubectl.kubernetes.io/last-applied-configuration"])
    m = {k: v for k, v in o["metadata"].items() if k not in DROP_META}
    ann = {k: v for k, v in (m.get("annotations") or {}).items() if not k.startswith(DROP_ANN_PREFIX)}
    lab = {k: v for k, v in (m.get("labels") or {}).items() if k not in DROP_LABELS}
    m.pop("annotations", None)
    m.pop("labels", None)
    if lab:
        m["labels"] = lab
    if ann:
        m["annotations"] = ann
    out = {"apiVersion": o["apiVersion"], "kind": o["kind"], "metadata": m}
    for k in ("spec", "data"):
        if k in o and not (o["kind"] == "Namespace" and k == "spec"):
            out[k] = o[k]
    return out


def write(fname, header, objs):
    with open(os.path.join(BASE, fname), "w") as f:
        f.write(header.rstrip() + "\n")
        for o in objs:
            f.write("---\n")
            yaml.safe_dump(clean(o), f, sort_keys=False, default_flow_style=False, width=120)
    print("wrote", fname, len(objs), "objects")


H = "# NGC-809 — exported live from CWL (OCP 4.22.3) on 2026-11-11 by ngc-809/tools/clean_export.py.\n"
pods = {p["metadata"]["name"]: p for p in load("x_pod.json")}
write("01-namespace.yaml", H + "# Namespace for all NGC-809 test pods.", load("x_ns.json"))
write("02-nncp-vf-partition.yaml", H + "# NMState: create 2 VFs on ens1f0np0 per node, trust/spoofchk and the 25 %/75 % rates\n"
      "# (VF0 6250/6250, VF1 18750/18750). Wait for NNCE Available before step 03.", load("x_nncp.json"))
write("03-sriovnetworknodepolicies.yaml", H + "# SR-IOV operator: map VF0 / VF1 of each node to kubelet resources (externallyManaged: nmstate owns the VFs).\n"
      "# WARNING: applying/changing these makes sriov-network-config-daemon rebind VFs that are attached to running pods.\n"
      "# Apply BEFORE the pods and wait until both SriovNetworkNodeStates are Succeeded and the resources are allocatable.",
      load("x_snnp.json"))
write("04-sriovnetworks.yaml", H + "# SriovNetworks (generate the NADs in ns dpdk): VLAN 206, trust, per-VF min/max rate, IPAM.", load("x_sn.json"))
write("05-configmaps-trex.yaml", H + "# TRex config template, port bandwidth and STL profile mounted into the trex pod.", load("x_cm.json"))
write("06-pods-trex-testpmd.yaml", H + "# VF1 (75 %) workloads: TRex (appworker-1) and testpmd (master-0). Pinned via nodeName.\n"
      "# After Ready, restore the in-pod files with tools/restore_pod_files.sh (pod-files/).",
      [pods["trex"], pods["testpmd"]])
write("07-pods-iperf3.yaml", H + "# VF0 (25 %) workloads: iperf3 server (master-0, 10.10.30.1) and client (appworker-1, 10.10.30.2).\n"
      "# Image quay.io/midu/iperf3:latest pinned by digest (Fedora 41 + iperf3 3.17.1).",
      [pods["iperf3-server"], pods["iperf3-client"]])
write("_reference/nads-generated-by-sriovnetwork.yaml", H + "# REFERENCE ONLY — do not apply: generated by the SR-IOV operator from 04-sriovnetworks.yaml.",
      load("x_nad.json"))
write("_reference/sriovoperatorconfig-default.yaml", H + "# REFERENCE ONLY — cluster-wide operator config in effect during the tests (disableDrain: true).",
      load("x_sriovopcfg.json"))
write("_reference/performanceprofile-appworker-mcp-a.yaml", H + "# REFERENCE ONLY — PerformanceProfile on appworker-1 (isolated CPUs, 1G hugepages, runtimeClass used by trex).\n"
      "# Pre-existing cluster tuning; applying it reboots the appworker-mcp-a pool.", load("x_pao.json"))
